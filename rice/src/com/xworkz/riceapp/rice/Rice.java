package com.xworkz.riceapp.rice;

public class Rice {

    private int riceId;
    private String riceType;
    private String riceBrand;
    private String riceOrigin;
    private String riceQuantity;
    private String riceQuality;
    private String ricePrice;

    // riceId
    public void setRiceId(int riceId) {
        this.riceId = riceId;
    }

    public int getRiceId() {
        return riceId;
    }

    // riceType
    public void setRiceType(String riceType) {
        this.riceType = riceType;
    }

    public String getRiceType() {
        return riceType;
    }

    // riceBrand
    public void setRiceBrand(String riceBrand) {
        this.riceBrand = riceBrand;
    }

    public String getRiceBrand() {
        return riceBrand;
    }

    // riceOrigin
    public void setRiceOrigin(String riceOrigin) {
        this.riceOrigin = riceOrigin;
    }

    public String getRiceOrigin() {
        return riceOrigin;
    }

    // riceQuantity
    public void setRiceQuantity(String riceQuantity) {
        this.riceQuantity = riceQuantity;
    }

    public String getRiceQuantity() {
        return riceQuantity;
    }

    // riceQuality
    public void setRiceQuality(String riceQuality) {
        this.riceQuality = riceQuality;
    }

    public String getRiceQuality() {
        return riceQuality;
    }

    // ricePrice
    public void setRicePrice(String ricePrice) {
        this.ricePrice = ricePrice;
    }

    public String getRicePrice() {
        return ricePrice;
    }
}
