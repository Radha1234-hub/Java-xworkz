package com.xworkz.metalapp.metal;

public class Metal {
    public void properties() {
        System.out.println("Metals are generally shiny, conductive, malleable, and have high melting points.");
    }

    public void uses() {
        System.out.println("Metals are used in construction, manufacturing, electronics, and jewelry.");
    }

    public void types() {
        System.out.println("Common types of metals include ferrous metals like iron and non-ferrous metals like copper.");
    }

    public void density() {
        System.out.println("Metals typically have high density and are heavy for their size.");
    }

    public void reactions() {
        System.out.println("Metals react with oxygen to form oxides, and some can react with acids to release hydrogen.");
    }
}
