class TubeLight{

	int id;
	String brand;	
	String color;	
	String material;
	String style;
	String lightFixtureForm;
	
	//zero parameterized
	TubeLight(){
	System.out.println("The zero parameterized constructor TubeLight is invoked");
	
	}
	
	//parameterized
	TubeLight(int id,String brand,String color,String material,String style,String lightFixtureForm){
	System.out.println("The zero parameterized constructor TubeLight is invoked");
		this.id = id;
		this.brand = brand;
		this.color = color;
		this.material = material;
		this.style = style;
		this.lightFixtureForm = lightFixtureForm;
	
	}


























}