package com.xworkz.gasesapp.gases;

public class Gases {
    public void composition() {
        System.out.println("Gases are composed of molecules that are in constant random motion.");
    }

    public void properties() {
        System.out.println("Gases are compressible, have low density, and can expand to fill their containers.");
    }

    public void uses() {
        System.out.println("Different gases are used in industries, healthcare, and research.");
    }

    public void occurrence() {
        System.out.println("Gases occur naturally in the atmosphere, underwater, or are produced artificially.");
    }

    public void behavior() {
        System.out.println("Gases obey physical laws such as Boyle's Law and Charles's Law.");
    }
}
