package com.xworkz.fuelapp.fuel;

public class Fuel {

    public void type() {
        System.out.println("Fuels include various types such as solid, liquid, and gaseous forms.");
    }

    public void purpose() {
        System.out.println("Fuels are used for energy generation, transportation, heating, and industrial processes.");
    }

    public void source() {
        System.out.println("Fuels are sourced from natural resources like fossil fuels, biomass, or synthetic processes.");
    }

    public void efficiency() {
        System.out.println("The efficiency of fuels depends on their energy output per unit of consumption.");
    }

    public void environmentalImpact() {
        System.out.println("Fuels can have varying environmental impacts, such as greenhouse gas emissions and pollution.");
    }
}
