package com.xworkz.oceanapp.indianocean;

import com.xworkz.oceanapp.ocean.Ocean;

public class IndianOcean extends Ocean {
    @Override
    public void name() {
        System.out.println("The Indian Ocean is the third-largest ocean, named after the Indian subcontinent.");
    }

    @Override
    public void size() {
        System.out.println("The Indian Ocean spans approximately 70.56 million square kilometers.");
    }

    @Override
    public void depth() {
        System.out.println("The Indian Ocean has an average depth of 3,741 meters, with the Java Trench as its deepest point.");
    }

    @Override
    public void marineLife() {
        System.out.println("The Indian Ocean supports marine life like dugongs, tuna, sharks, and coral reefs.");
    }

    @Override
    public void importance() {
        System.out.println("The Indian Ocean is vital for monsoon systems, maritime trade, and regional ecosystems.");
    }

    public void borderingCountries() {
        System.out.println("Countries bordering the Indian Ocean include India, Australia, Indonesia, and Madagascar.");
    }

    public void uniqueFeatures() {
        System.out.println("The Indian Ocean is known for its warm waters, monsoon currents, and unique biodiversity.");
    }
}
