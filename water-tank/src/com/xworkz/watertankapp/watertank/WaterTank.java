package com.xworkz.tankapp.tank;

public class WaterTank {

    private int tankId;
    private String tankMaterial;
    private String tankCapacity;
    private String tankColor;
    private String tankShape;
    private String tankHeight;
    private String tankDiameter;

    // tankId
    public void setTankId(int tankId) {
        this.tankId = tankId;
    }

    public int getTankId() {
        return tankId;
    }

    // tankMaterial
    public void setTankMaterial(String tankMaterial) {
        this.tankMaterial = tankMaterial;
    }

    public String getTankMaterial() {
        return tankMaterial;
    }

    // tankCapacity
    public void setTankCapacity(String tankCapacity) {
        this.tankCapacity = tankCapacity;
    }

    public String getTankCapacity() {
        return tankCapacity;
    }

    // tankColor
    public void setTankColor(String tankColor) {
        this.tankColor = tankColor;
    }

    public String getTankColor() {
        return tankColor;
    }

    // tankShape
    public void setTankShape(String tankShape) {
        this.tankShape = tankShape;
    }

    public String getTankShape() {
        return tankShape;
    }

    // tankHeight
    public void setTankHeight(String tankHeight) {
        this.tankHeight = tankHeight;
    }

    public String getTankHeight() {
        return tankHeight;
    }

    // tankDiameter
    public void setTankDiameter(String tankDiameter) {
        this.tankDiameter = tankDiameter;
    }

    public String getTankDiameter() {
        return tankDiameter;
    }
}
