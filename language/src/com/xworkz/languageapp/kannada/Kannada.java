package com.xworkz.languageapp.kannada;

import com.xworkz.languageapp.language.Language;

public class Kannada extends Language {
    @Override
    public void origin() {
        System.out.println("Kannada originated in Karnataka, India, and has a history dating back over 2,000 years.");
    }

    @Override
    public void script() {
        System.out.println("Kannada uses its own script, derived from the Kadamba script, and is one of the oldest scripts in India.");
    }

    @Override
    public void speakers() {
        System.out.println("Kannada is spoken by over 44 million people, primarily in Karnataka.");
    }

    @Override
    public void usage() {
        System.out.println("Kannada is used in literature, cinema, education, and official communication in Karnataka.");
    }

    @Override
    public void significance() {
        System.out.println("Kannada is recognized as one of the classical languages of India, showcasing rich cultural heritage.");
    }

    public void literaryAchievements() {
        System.out.println("Kannada boasts eminent poets and writers, including Kuvempu, whose works have gained national recognition.");
    }

    public void festivalsCelebrated() {
        System.out.println("Kannada Rajyotsava is celebrated annually to honor the formation of Karnataka and the Kannada language.");
    }
}
