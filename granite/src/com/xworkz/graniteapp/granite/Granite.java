package com.xworkz.graniteapp.granite;

public class Granite {

    private int graniteId;
    private String graniteType;
    private String graniteOrigin;
    private String graniteLength;
    private String graniteWidth;
    private String graniteThickness;
    private String granitePurpose;

    //graniteId
    public void setGraniteId(int graniteId) {
        this.graniteId = graniteId;
    }

    public int getGraniteId() {
        return graniteId;
    }

    //graniteType

    public void setGraniteType(String graniteType) {
        this.graniteType = graniteType;
    }

    public String getGraniteType() {
        return graniteType;
    }

    //graniteOrigin

    public void setGraniteOrigin(String graniteOrigin) {
        this.graniteOrigin = graniteOrigin;
    }

    public String getGraniteOrigin() {
        return graniteOrigin;
    }

    //graniteLength

    public void setGraniteLength(String graniteLength) {
        this.graniteLength = graniteLength;
    }

    public String getGraniteLength() {
        return graniteLength;
    }

    //graniteWidth

    public void setGraniteWidth(String graniteWidth) {
        this.graniteWidth = graniteWidth;
    }

    public String getGraniteWidth() {
        return graniteWidth;
    }

    //graniteThickiness

    public void setGraniteThickness(String graniteThickness) {
        this.graniteThickness = graniteThickness;
    }

    public String getGraniteThickness() {
        return graniteThickness;
    }

    //granitePurpose

    public void setGranitePurpose(String granitePurpose) {
        this.granitePurpose = granitePurpose;
    }

    public String getGranitePurpose() {
        return granitePurpose;
    }
}
