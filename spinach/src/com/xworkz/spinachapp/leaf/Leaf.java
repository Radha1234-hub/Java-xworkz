package com.xworkz.spinachapp.leaf;

public class Leaf {


        public void type() {
            System.out.println("Leaves are the green, flat structures of plants responsible for photosynthesis.");
        }

        public void color() {
            System.out.println("Leaves are typically green due to the presence of chlorophyll.");
        }

        public void shape() {
            System.out.println("Leaves come in various shapes, such as oval, lanceolate, or heart-shaped.");
        }

        public void function() {
            System.out.println("Leaves perform photosynthesis, transpiration, and gas exchange in plants.");
        }

        public void significance() {
            System.out.println("Leaves play a vital role in the ecosystem as primary producers of oxygen and food.");
        }
}
