package com.xworkz.desertapp.sahara;

import com.xworkz.desertapp.desert.Desert;

public class Sahara extends Desert {


    @Override
    public void climate() {
        System.out.println("The Sahara Desert experiences extreme arid conditions, with very high temperatures and minimal rainfall.");
    }

    @Override
    public void vegetation() {
        System.out.println("The Sahara Desert has limited vegetation, including hardy plants like cacti and acacias.");
    }

    @Override
    public void wildlife() {
        System.out.println("The Sahara is home to camels, fennec foxes, scorpions, and desert-adapted birds.");
    }

    @Override
    public void terrain() {
        System.out.println("The Sahara features vast sand dunes, rocky plateaus, and occasional oases.");
    }

    @Override
    public void significance() {
        System.out.println("The Sahara Desert is culturally significant and holds geological importance as the largest hot desert in the world.");
    }

    public void size() {
        System.out.println("The Sahara Desert spans approximately 9.2 million square kilometers across Northern Africa.");
    }

    public void uniqueFeatures() {
        System.out.println("The Sahara contains oases, ancient trade routes, and remnants of prehistoric human settlements.");
    }

}
