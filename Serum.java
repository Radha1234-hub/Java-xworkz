class Serum{

	int id ;
	String productBenefits;
	String scent;
	String liquidVolume;
	String itemForm;
	String brand;
	
	//zero parameterized
	Serum(){
	System.out.println("The zero parameterized constructor Serum is invoked");
	}
	
	//parameterized
	Serum(int id ,String productBenefits,String scent,String liquidVolume,String itemForm,String brand){
	System.out.println("The zero parameterized constructor Serum is invoked");
		this.id = id;
		this.productBenefits = productBenefits;
		this.scent = scent;
		this.liquidVolume = liquidVolume;
		this.itemForm = itemForm;
		this.brand = brand;

	}





































}