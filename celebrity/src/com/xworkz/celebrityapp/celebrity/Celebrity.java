package com.xworkz.celebrityapp.celebrity;

public class Celebrity {

    private int celebrityId;
    private String celebrityName;
    private String celebrityProfession;
    private String celebrityNationality;
    private String celebrityAchievements;
    private String celebrityNetWorth;
    private String celebrityBirthDate;

    // celebrityId
    public void setCelebrityId(int celebrityId) {
        this.celebrityId = celebrityId;
    }

    public int getCelebrityId() {
        return celebrityId;
    }

    // celebrityName
    public void setCelebrityName(String celebrityName) {
        this.celebrityName = celebrityName;
    }

    public String getCelebrityName() {
        return celebrityName;
    }

    // celebrityProfession
    public void setCelebrityProfession(String celebrityProfession) {
        this.celebrityProfession = celebrityProfession;
    }

    public String getCelebrityProfession() {
        return celebrityProfession;
    }

    // celebrityNationality
    public void setCelebrityNationality(String celebrityNationality) {
        this.celebrityNationality = celebrityNationality;
    }

    public String getCelebrityNationality() {
        return celebrityNationality;
    }

    // celebrityAchievements
    public void setCelebrityAchievements(String celebrityAchievements) {
        this.celebrityAchievements = celebrityAchievements;
    }

    public String getCelebrityAchievements() {
        return celebrityAchievements;
    }

    // celebrityNetWorth
    public void setCelebrityNetWorth(String celebrityNetWorth) {
        this.celebrityNetWorth = celebrityNetWorth;
    }

    public String getCelebrityNetWorth() {
        return celebrityNetWorth;
    }

    // celebrityBirthDate
    public void setCelebrityBirthDate(String celebrityBirthDate) {
        this.celebrityBirthDate = celebrityBirthDate;
    }

    public String getCelebrityBirthDate() {
        return celebrityBirthDate;
    }
}
