class CoolDrink{

	int id;
	String brand;
	String itemForm;	
	String flavor;
	int numberOfItems;	
	String packageInformation;
	
	//zero parameterized
	CoolDrink(){
	System.out.println("The zero parameterized constructor CoolDrink is invoked");
	}

	//zero parameterized
	CoolDrink(int id,String brand,String itemForm,	String flavor,int numberOfItems,String packageInformation){
	System.out.println("The parameterized constructor CoolDrink is invoked");
		this.id = id;
		this.brand = brand;
		this.itemForm = itemForm;
		this.flavor = flavor;
		this.numberOfItems = numberOfItems;
		this.packageInformation = packageInformation;
	
	}





























































}