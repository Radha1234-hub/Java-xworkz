package com.xworkz.ladderapp.ladder;

public class Ladder {

    private int ladderId;
    private String ladderMaterial;
    private String ladderHeight;
    private String ladderWidth;
    private String ladderWeightCapacity;
    private String ladderType;
    private String ladderColor;

    // ladderId
    public void setLadderId(int ladderId) {
        this.ladderId = ladderId;
    }

    public int getLadderId() {
        return ladderId;
    }

    // ladderMaterial
    public void setLadderMaterial(String ladderMaterial) {
        this.ladderMaterial = ladderMaterial;
    }

    public String getLadderMaterial() {
        return ladderMaterial;
    }

    // ladderHeight
    public void setLadderHeight(String ladderHeight) {
        this.ladderHeight = ladderHeight;
    }

    public String getLadderHeight() {
        return ladderHeight;
    }

    // ladderWidth
    public void setLadderWidth(String ladderWidth) {
        this.ladderWidth = ladderWidth;
    }

    public String getLadderWidth() {
        return ladderWidth;
    }

    // ladderWeightCapacity
    public void setLadderWeightCapacity(String ladderWeightCapacity) {
        this.ladderWeightCapacity = ladderWeightCapacity;
    }

    public String getLadderWeightCapacity() {
        return ladderWeightCapacity;
    }

    // ladderType
    public void setLadderType(String ladderType) {
        this.ladderType = ladderType;
    }

    public String getLadderType() {
        return ladderType;
    }

    // ladderColor
    public void setLadderColor(String ladderColor) {
        this.ladderColor = ladderColor;
    }

    public String getLadderColor() {
        return ladderColor;
    }
}
