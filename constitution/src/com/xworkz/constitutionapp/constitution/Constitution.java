package com.xworkz.constitutionapp.constitution;

public class Constitution {

    private int constitutionId;
    private String constitutionTitle;
    private String constitutionCountry;
    private String constitutionLanguage;
    private String constitutionEdition;
    private String constitutionPublisher;
    private String constitutionYear;

    // constitutionId
    public void setConstitutionId(int constitutionId) {
        this.constitutionId = constitutionId;
    }

    public int getConstitutionId() {
        return constitutionId;
    }

    // constitutionTitle
    public void setConstitutionTitle(String constitutionTitle) {
        this.constitutionTitle = constitutionTitle;
    }

    public String getConstitutionTitle() {
        return constitutionTitle;
    }

    // constitutionCountry
    public void setConstitutionCountry(String constitutionCountry) {
        this.constitutionCountry = constitutionCountry;
    }

    public String getConstitutionCountry() {
        return constitutionCountry;
    }

    // constitutionLanguage
    public void setConstitutionLanguage(String constitutionLanguage) {
        this.constitutionLanguage = constitutionLanguage;
    }

    public String getConstitutionLanguage() {
        return constitutionLanguage;
    }

    // constitutionEdition
    public void setConstitutionEdition(String constitutionEdition) {
        this.constitutionEdition = constitutionEdition;
    }

    public String getConstitutionEdition() {
        return constitutionEdition;
    }

    // constitutionPublisher
    public void setConstitutionPublisher(String constitutionPublisher) {
        this.constitutionPublisher = constitutionPublisher;
    }

    public String getConstitutionPublisher() {
        return constitutionPublisher;
    }

    // constitutionYear
    public void setConstitutionYear(String constitutionYear) {
        this.constitutionYear = constitutionYear;
    }

    public String getConstitutionYear() {
        return constitutionYear;
    }
}
