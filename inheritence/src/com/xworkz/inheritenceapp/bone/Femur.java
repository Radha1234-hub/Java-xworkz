public class Femur extends Bone{

    public void femurDetails() {
        System.out.println("The femur, also known as the thigh bone, is the longest and strongest bone in the body.");
    }

    public void femurStrength() {
        System.out.println("The femur can withstand significant pressure and weight.");
    }

    public void femurLocation() {
        System.out.println("The femur is located in the upper leg, connecting the hip to the knee.");
    }

    public void femurFunctionality() {
        System.out.println("The femur supports walking, running, and jumping.");
    }
}
