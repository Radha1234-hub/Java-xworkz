package com.xworkz.inheritenceapp.hormone;

public class Insulin extends Hormone{
    public void insulinRole() {
        System.out.println("Role: Insulin helps regulate blood sugar levels by facilitating glucose absorption.");
    }

    public void insulinSecretion() {
        System.out.println("Secretion: Insulin is secreted by the beta cells of the pancreas.");
    }

    public void insulinDeficiency() {
        System.out.println("Deficiency: Lack of insulin leads to diabetes, requiring medication or insulin therapy.");
    }

    public void insulinDiscovery() {
        System.out.println("Discovery: Insulin was discovered in 1921 and revolutionized diabetes treatment.");
    }
}
