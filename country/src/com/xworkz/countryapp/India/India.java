package com.xworkz.countryapp.India;

import com.xworkz.countryapp.country.Country;

public class India extends Country {
    @Override
    public void name() {
        System.out.println("India is a culturally rich and diverse country located in South Asia.");
    }

    @Override
    public void population() {
        System.out.println("India has a population of over 1.4 billion, making it the second most populous country in the world.");
    }

    @Override
    public void capital() {
        System.out.println("The capital of India is New Delhi, which serves as the administrative and political hub.");
    }

    @Override
    public void economy() {
        System.out.println("India has a mixed economy, including sectors like agriculture, IT, manufacturing, and services.");
    }

    @Override
    public void language() {
        System.out.println("India has 22 official languages, with Hindi and English being widely used for governance.");
    }

    public void culturalDiversity() {
        System.out.println("India is known for its cultural diversity, including festivals, cuisines, and traditions.");
    }

    public void historicalSignificance() {
        System.out.println("India has a rich history, being home to ancient civilizations like the Indus Valley and iconic landmarks such as the Taj Mahal.");
    }

}
