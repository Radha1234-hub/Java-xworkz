package com.xworkz.kingapp.ashoka;

import com.xworkz.kingapp.king.King;

public class Ashoka extends King
{
    @Override
    public void reign() {
        System.out.println("Ashoka ruled the Mauryan Empire from 268 to 232 BCE, expanding it to its peak.");
    }

    @Override
    public void achievements() {
        System.out.println("Ashoka is known for his victory in the Kalinga War and his subsequent embrace of Buddhism.");
    }

    @Override
    public void governance() {
        System.out.println("Ashoka governed with principles inspired by Buddhism, promoting welfare, nonviolence, and moral responsibility.");
    }

    @Override
    public void legacy() {
        System.out.println("Ashoka's legacy includes the spread of Buddhism, the Ashokan Edicts, and his symbol on India's national emblem.");
    }

    @Override
    public void titles() {
        System.out.println("Ashoka is known as 'Ashoka the Great' and 'Devanampriya' (Beloved of the Gods).");
    }

    public void edicts() {
        System.out.println("Ashoka's edicts were inscribed on pillars and rocks, spreading messages of dharma and morality.");
    }

    public void transformation() {
        System.out.println("Ashoka's transformation after the Kalinga War marked a shift from conquest to peace and spirituality.");
    }
}
