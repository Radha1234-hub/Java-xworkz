package com.xworkz.bloodcellapp.bloodcell;

public class BloodCell {
    public void type() {
        System.out.println("Blood cells include red blood cells (RBCs), white blood cells (WBCs), and platelets.");
    }

    public void function() {
        System.out.println("Blood cells serve various functions such as oxygen transport, immune defense, and clotting.");
    }

    public void production() {
        System.out.println("Blood cells are produced in the bone marrow through the process of hematopoiesis.");
    }

    public void lifespan() {
        System.out.println("Blood cells have different lifespans, ranging from a few days to months.");
    }

    public void structure() {
        System.out.println("Blood cells vary in structure, such as biconcave shapes for RBCs or granular appearances for WBCs.");
    }
}
