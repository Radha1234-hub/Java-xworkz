package com.xworkz.virusapp.virus;

public class Virus {
    public void type() {
        System.out.println("Viruses are microscopic infectious agents that can replicate only inside living cells.");
    }

    public void structure() {
        System.out.println("Viruses are composed of genetic material (DNA or RNA) enclosed in a protein coat called a capsid.");
    }

    public void transmission() {
        System.out.println("Viruses spread through various modes like airborne particles, physical contact, or fluids.");
    }

    public void impact() {
        System.out.println("Viruses cause diseases in humans, animals, and plants, ranging from mild to severe.");
    }

    public void replication() {
        System.out.println("Viruses replicate by infecting host cells and using their machinery to reproduce.");
    }
}
