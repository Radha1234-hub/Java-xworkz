package com.xworkz.tilesapp.tiles;

public class Tiles {

    private int tileId;
    private String tileMaterial;
    private String tileColor;
    private String tileFinish;
    private String tileLength;
    private String tileWidth;
    private String tileThickness;
    private String tilePurpose;

    // tileId
    public void setTileId(int tileId) {
        this.tileId = tileId;
    }

    public int getTileId() {
        return tileId;
    }

    // tileMaterial
    public void setTileMaterial(String tileMaterial) {
        this.tileMaterial = tileMaterial;
    }

    public String getTileMaterial() {
        return tileMaterial;
    }

    // tileColor
    public void setTileColor(String tileColor) {
        this.tileColor = tileColor;
    }

    public String getTileColor() {
        return tileColor;
    }

    // tileFinish
    public void setTileFinish(String tileFinish) {
        this.tileFinish = tileFinish;
    }

    public String getTileFinish() {
        return tileFinish;
    }

    // tileLength
    public void setTileLength(String tileLength) {
        this.tileLength = tileLength;
    }

    public String getTileLength() {
        return tileLength;
    }

    // tileWidth
    public void setTileWidth(String tileWidth) {
        this.tileWidth = tileWidth;
    }

    public String getTileWidth() {
        return tileWidth;
    }

    // tileThickness
    public void setTileThickness(String tileThickness) {
        this.tileThickness = tileThickness;
    }

    public String getTileThickness() {
        return tileThickness;
    }

    // tilePurpose
    public void setTilePurpose(String tilePurpose) {
        this.tilePurpose = tilePurpose;
    }

    public String getTilePurpose() {
        return tilePurpose;
    }
}
