package com.xworkz.organiccompoundapp.organiccompound;

public class OrganicCompound {
    public void definition() {
        System.out.println("Organic compounds are chemical compounds primarily made of carbon and hydrogen atoms.");
    }

    public void structure() {
        System.out.println("Organic compounds can have various structures, such as chains, rings, or branches.");
    }

    public void classification() {
        System.out.println("Organic compounds are classified into alkanes, alkenes, alkynes, alcohols, aldehydes, and more.");
    }

    public void uses() {
        System.out.println("Organic compounds are used in pharmaceuticals, plastics, fuels, and many industrial applications.");
    }

    public void importance() {
        System.out.println("Organic compounds are essential for life and many modern technologies.");
    }
}
